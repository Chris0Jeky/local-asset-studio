'use strict';
const assert=require('node:assert/strict');
const C=require('../app/static/scene-brief-core.js');
const workspace='a'.repeat(32),card=C.newCard(workspace,'brief-one');
assert(C.validBody(card.body));
const raw=JSON.stringify(C.envelope(card,null));
assert.deepEqual(C.recovery(raw,workspace,card.id).card,card);
for(const broken of ['{',JSON.stringify({...C.envelope(card,null),format:'future'}),JSON.stringify(C.envelope({...card,body:{...card.body,extra:true}},null))])assert.throws(()=>C.recovery(broken,workspace,card.id));
assert.throws(()=>C.recovery(raw,'b'.repeat(32),card.id));
const asset={id:'real-asset',sha256:'b'.repeat(64),metadata_revision:7,media_type:'image'};
const first=C.choose(card,'background',asset),next=C.choose(first,'background',{...asset,id:'replacement'});
assert.equal(card.body.slots.background.selected,null);
assert.equal(next.body.slots.background.previous.asset_id,'real-asset');
assert.throws(()=>C.choose(card,'audio',asset));assert.throws(()=>C.choose(card,'background',{...asset,privacy:'private'}));
assert.throws(()=>C.choose(card,'background',{...asset,archived_at:12}));
assert.throws(()=>C.choose(card,'background',{...asset,sha256:'bad'}));
const route={id:card.id,slot:'audio',picker:true,q:'quiet water & birds',cursor:'real-cursor',returned:7};
assert.deepEqual(C.route(C.hash(route)),{...route,view:'briefs'});
assert.equal(C.route('#briefs?id=../../escape&slot=constructor').id,null);
assert.equal(C.route('#briefs?slot=constructor').slot,'background');
assert(C.context({workspace_id:workspace,id:card.id,revision:0,slot:'mesh'}));
assert(!C.context({workspace_id:workspace,id:card.id,revision:-1,slot:'mesh'}));
console.log('Scene brief recovery, replacement, type/privacy boundaries and navigation passed.');
