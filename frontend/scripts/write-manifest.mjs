// Writes app/static/ui-dist/manifest.json after `vite build`: source entry -> output files with SHA-256, raw and
// gzip sizes, the pinned toolchain and the payload budget. Fails when the output holds anything the unchanged
// Python static handler cannot serve (.js/.css only) or when the island exceeds its gzip budget.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = new URL('..', import.meta.url);
const dist = fileURLToPath(new URL('../app/static/ui-dist/', here));
const BUDGET_GZIP_BYTES = 150 * 1024;
const SERVABLE = /\.(?:js|css)$/;

const lock = JSON.parse(readFileSync(new URL('package-lock.json', here), 'utf8'));
const pkg = JSON.parse(readFileSync(new URL('package.json', here), 'utf8'));
const nvmrc = readFileSync(new URL('.nvmrc', here), 'utf8').trim();
if (process.version !== 'v' + nvmrc) console.warn(`[manifest] building with ${process.version}; the pinned toolchain is v${nvmrc}`);

const names = readdirSync(dist).sort();
const stray = names.filter(name => name !== 'manifest.json' && (!SERVABLE.test(name) || !statSync(dist + name).isFile()));
if (stray.length) throw new Error('ui-dist holds files the Python static handler will not serve: ' + stray.join(', '));

const files = {};
let gzipTotal = 0;
for (const name of names.filter(name => SERVABLE.test(name))) {
  const data = readFileSync(dist + name);
  const gzipBytes = gzipSync(data, { level: 9 }).length;
  gzipTotal += gzipBytes;
  files[name] = { sha256: createHash('sha256').update(data).digest('hex'), bytes: data.length, gzipBytes };
}
if (!files['island.js'] || !files['island.css']) throw new Error('Expected island.js and island.css in ui-dist');
if (gzipTotal > BUDGET_GZIP_BYTES) throw new Error(`Island payload ${gzipTotal} B gzip exceeds the ${BUDGET_GZIP_BYTES} B budget`);

const direct = Object.keys({ ...pkg.dependencies, ...pkg.devDependencies }).sort();
const manifest = {
  version: 1,
  note: 'Generated by frontend/scripts/write-manifest.mjs. Do not edit. Rebuild with: cd frontend && npm ci && npm run build',
  entries: { 'src/main.ts': { file: 'island.js', css: ['island.css'], loadedBy: 'app/static/studio-shell.js (?ui=island)' } },
  files,
  budget: { gzipLimitBytes: BUDGET_GZIP_BYTES, gzipTotalBytes: gzipTotal },
  toolchain: {
    node: nvmrc,
    packages: Object.fromEntries(direct.map(name => [name, lock.packages['node_modules/' + name].version])),
    lockfileSha256: createHash('sha256').update(readFileSync(new URL('package-lock.json', here))).digest('hex')
  }
};
writeFileSync(dist + 'manifest.json', JSON.stringify(manifest, null, 2) + '\n');
console.log(`[manifest] ${Object.keys(files).join(', ')} · ${gzipTotal} B gzip of ${BUDGET_GZIP_BYTES} B budget`);
